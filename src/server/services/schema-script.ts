/**
 * Per-repo schema EXTRACTOR SCRIPTS: generation, storage, execution.
 *
 * Instead of shipping a parser per stack, each repo gets its own extractor
 * written by a Claude Code agent that reads the actual codebase. The agent's
 * job is narrow and fixed: emit a script that prints the repo's DECLARED schema
 * as JSON in the contract below. Everything downstream — diagram, diff — only
 * ever sees that contract, so any stack works as long as its script does.
 *
 * Scripts live in the board's data dir (`<dataDir>/schema-scripts/<repoId>.sh`),
 * keyed by project repo, so every task on that repo shares one script and no
 * user repository is polluted.
 *
 * The script is generated by an agent and then EXECUTED locally, which is the
 * design the feature asks for. Two guards keep that honest: generation runs the
 * agent with read-only tools, and the script's output is fully validated here —
 * a malformed or hostile payload yields warnings and dropped entries, never
 * unchecked data downstream.
 */
import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

import type {
  SchemaEntity,
  SchemaField,
  SchemaGraph,
  SchemaRelation,
} from "../../shared/types.js";

const execFileAsync = promisify(execFile);

/** How long a generated extractor may run before being killed. */
const RUN_TIMEOUT_MS = 30_000;
/**
 * How long the generating agent may take. Generous on purpose: it reads a whole
 * codebase and tests its own script, and it runs as a background job, so a slow
 * repo costs patience rather than a failed request.
 */
const GENERATE_TIMEOUT_MS = 30 * 60_000;
/** Cap on a script's stdout. */
const MAX_OUTPUT_BYTES = 32 * 1024 * 1024;
/** Defensive caps on what a script may declare. */
const MAX_ENTITIES = 2000;
const MAX_FIELDS_PER_ENTITY = 500;
const MAX_RELATIONS = 5000;

/** Result of parsing a script's output. */
export interface ExtractResult {
  entities: SchemaEntity[];
  relations: SchemaRelation[];
  /** Non-fatal problems found while validating the payload. */
  warnings: string[];
  /** Free-form dialect label the script reported (e.g. "rails", "prisma"). */
  dialect: string;
}

/** Raised when a script cannot be run or its output cannot be trusted. */
export class SchemaScriptError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SchemaScriptError";
  }
}

/* ────────────────────────────────────────────────────────────────────────
 * Storage
 * ──────────────────────────────────────────────────────────────────────── */

/** Where a project repo's extractor lives. */
export function scriptPathFor(dataDir: string, projectRepoId: string): string {
  return path.join(dataDir, "schema-scripts", `${safeId(projectRepoId)}.sh`);
}

/** Sidecar holding when the script was generated and what it detected. */
export function metaPathFor(dataDir: string, projectRepoId: string): string {
  return path.join(dataDir, "schema-scripts", `${safeId(projectRepoId)}.json`);
}

/** Ids come from the database, but never interpolate one into a path raw. */
const safeId = (id: string): string => id.replace(/[^A-Za-z0-9_-]/g, "_");

export interface ScriptMeta {
  generatedAt: string;
  /** The agent's one-line description of what it found. */
  summary: string;
}

export async function readMeta(
  dataDir: string,
  projectRepoId: string,
): Promise<ScriptMeta | null> {
  try {
    const raw = await fs.readFile(metaPathFor(dataDir, projectRepoId), "utf8");
    const parsed: unknown = JSON.parse(raw);
    if (!isRecord(parsed)) return null;
    return {
      generatedAt: String(parsed.generatedAt ?? ""),
      summary: String(parsed.summary ?? ""),
    };
  } catch {
    return null;
  }
}

export async function scriptExists(
  dataDir: string,
  projectRepoId: string,
): Promise<boolean> {
  try {
    await fs.access(scriptPathFor(dataDir, projectRepoId));
    return true;
  } catch {
    return false;
  }
}

/* ────────────────────────────────────────────────────────────────────────
 * Execution
 * ──────────────────────────────────────────────────────────────────────── */

/**
 * Run an extractor with `cwd` as the repo root and validate what it prints.
 * Throws {@link SchemaScriptError} when the script fails, times out, or emits
 * something that is not the contract.
 */
export async function runScript(
  scriptPath: string,
  cwd: string,
): Promise<ExtractResult> {
  let stdout: string;
  try {
    const res = await execFileAsync("bash", [scriptPath], {
      cwd,
      timeout: RUN_TIMEOUT_MS,
      maxBuffer: MAX_OUTPUT_BYTES,
      env: { ...process.env, CK_SCHEMA_REPO: cwd },
    });
    stdout = res.stdout;
  } catch (err) {
    const e = err as NodeJS.ErrnoException & { stderr?: string; killed?: boolean };
    if (e.killed) {
      throw new SchemaScriptError(
        `El script tardó más de ${RUN_TIMEOUT_MS / 1000}s y fue interrumpido.`,
      );
    }
    const detail = (e.stderr ?? e.message ?? "").trim().split("\n").slice(-4).join(" ");
    throw new SchemaScriptError(`El script falló: ${detail || "sin salida"}`);
  }
  return parseScriptOutput(stdout);
}

/**
 * Validate a script's stdout against the contract. Everything is checked and
 * coerced: unknown shapes are dropped with a warning rather than trusted, so a
 * bad generation degrades to a partial diagram instead of corrupt data.
 */
export function parseScriptOutput(stdout: string): ExtractResult {
  const warnings: string[] = [];
  const payload = extractJson(stdout);

  const rawEntities = Array.isArray(payload.entities) ? payload.entities : [];
  const rawRelations = Array.isArray(payload.relations) ? payload.relations : [];
  if (!Array.isArray(payload.entities)) {
    warnings.push("La salida no traía un array `entities`.");
  }

  const entities = parseEntities(rawEntities, warnings);
  // Las relaciones se validan CONTRA las tablas que sobrevivieron arriba, no
  // contra las que el script dijo tener: una FK a una tabla descartada apunta
  // a la nada igual que una a una tabla inexistente.
  const declared = new Set(entities.map((e) => e.name));
  const relations = parseRelations(rawRelations, declared, warnings);

  if (entities.length === 0) {
    throw new SchemaScriptError(
      "El script no declaró ninguna tabla. Revisá el script generado o volvé a generarlo.",
    );
  }

  return {
    entities,
    relations,
    warnings,
    dialect: asString(payload.dialect) ?? "generado",
  };
}

/** Coerce the declared tables, dropping the nameless and the duplicated. */
function parseEntities(raw: unknown[], warnings: string[]): SchemaEntity[] {
  if (raw.length > MAX_ENTITIES) {
    warnings.push(`Se ignoraron tablas por encima de ${MAX_ENTITIES}.`);
  }

  const entities: SchemaEntity[] = [];
  const seen = new Set<string>();
  for (const entity of raw.slice(0, MAX_ENTITIES)) {
    if (!isRecord(entity) || typeof entity.name !== "string" || entity.name.length === 0) {
      warnings.push("Se descartó una tabla sin nombre.");
      continue;
    }
    if (seen.has(entity.name)) {
      warnings.push(`Tabla duplicada: ${entity.name}.`);
      continue;
    }
    seen.add(entity.name);
    entities.push({
      name: entity.name,
      fields: parseFields(entity.fields, entity.name, warnings),
      sourceFile: asString(entity.sourceFile) ?? "",
      sourceLine: asPositiveInt(entity.sourceLine) ?? 0,
      pending: entity.pending === true,
    });
  }
  return entities;
}

/** Coerce the declared foreign keys, dropping the ones with no real endpoints. */
function parseRelations(
  raw: unknown[],
  declared: Set<string>,
  warnings: string[],
): SchemaRelation[] {
  const relations: SchemaRelation[] = [];
  for (const relation of raw.slice(0, MAX_RELATIONS)) {
    if (
      !isRecord(relation) ||
      typeof relation.from !== "string" ||
      typeof relation.to !== "string" ||
      relation.from.length === 0 ||
      relation.to.length === 0
    ) {
      warnings.push("Se descartó una relación sin extremos.");
      continue;
    }
    // A relation to a table that was never declared would render as a phantom
    // box in the diagram, so it is dropped rather than drawn.
    if (!declared.has(relation.from) || !declared.has(relation.to)) {
      warnings.push(
        `Relación ignorada por apuntar a una tabla inexistente: ${relation.from} → ${relation.to}.`,
      );
      continue;
    }
    relations.push({
      from: relation.from,
      to: relation.to,
      fromField: asString(relation.fromField) ?? "",
      onDelete: asString(relation.onDelete),
      sourceFile: asString(relation.sourceFile) ?? "",
      sourceLine: asPositiveInt(relation.sourceLine) ?? 0,
      pending: relation.pending === true,
    });
  }
  return relations;
}

function parseFields(
  raw: unknown,
  entityName: string,
  warnings: string[],
): SchemaField[] {
  if (!Array.isArray(raw)) return [];
  const fields: SchemaField[] = [];
  for (const f of raw.slice(0, MAX_FIELDS_PER_ENTITY)) {
    if (!isRecord(f) || typeof f.name !== "string" || f.name.length === 0) {
      warnings.push(`Columna sin nombre en ${entityName}.`);
      continue;
    }
    const field: SchemaField = {
      name: f.name,
      type: asString(f.type) ?? "",
      // Absent nullability reads as nullable, the laxer of the two.
      nullable: f.nullable !== false,
      primaryKey: f.primaryKey === true,
      pending: f.pending === true,
    };
    const def = asString(f.default);
    if (def !== null) field.default = def;
    fields.push(field);
  }
  return fields;
}

/**
 * Pull the JSON object out of a script's stdout. Pure JSON is expected, but a
 * script that also logs to stdout is common enough to be worth surviving, so
 * the outermost braces are used as a fallback.
 */
function extractJson(stdout: string): Record<string, unknown> {
  const trimmed = stdout.trim();
  if (trimmed.length === 0) {
    throw new SchemaScriptError("El script no imprimió nada.");
  }

  const attempt = (text: string): Record<string, unknown> | null => {
    try {
      const parsed: unknown = JSON.parse(text);
      return isRecord(parsed) ? parsed : null;
    } catch {
      return null;
    }
  };

  const direct = attempt(trimmed);
  if (direct) return direct;

  const start = trimmed.indexOf("{");
  const end = trimmed.lastIndexOf("}");
  if (start !== -1 && end > start) {
    const sliced = attempt(trimmed.slice(start, end + 1));
    if (sliced) return sliced;
  }

  throw new SchemaScriptError(
    `La salida del script no es JSON válido: ${trimmed.slice(0, 200)}`,
  );
}

