/** The contract the generated script must satisfy, as told to the agent. */
export const SCRIPT_CONTRACT = `{
  "dialect": "rails",
  "entities": [
    {
      "name": "posts",
      "sourceFile": "db/schema.rb",
      "sourceLine": 42,
      "fields": [
        { "name": "id", "type": "bigint", "nullable": false, "primaryKey": true },
        { "name": "user_id", "type": "bigint", "nullable": false },
        { "name": "title", "type": "string", "nullable": true, "default": "''" }
      ]
    }
  ],
  "relations": [
    {
      "from": "posts",
      "fromField": "user_id",
      "to": "users",
      "onDelete": "cascade",
      "sourceFile": "db/schema.rb",
      "sourceLine": 120
    }
  ]
}`;

/** Prompt handed to the generating agent. */
export function buildGenerationPrompt(repoName: string): string {
  return `Escribí un script de extracción de esquema para este repositorio (${repoName}).

CONTEXTO
Una herramienta va a ejecutar tu script para dibujar un diagrama entidad-relación
del esquema que este proyecto DECLARA EN SU CÓDIGO. El objetivo es ver la
estructura que describen los archivos (modelos de ORM, migraciones, schema.sql,
schema.prisma, models.py, entidades, etc.), NO los datos de una base corriendo.

TAREA
1. Explorá el repositorio y descubrí dónde está declarado el esquema. Puede ser
   cualquier stack. Si hay varias fuentes, elegí la más completa y autoritativa
   (por ejemplo un schema consolidado antes que migraciones sueltas), y
   considerá también las migraciones/archivos que todavía no estén reflejados
   ahí.
2. Escribí un script que imprima ese esquema como JSON en stdout.

REQUISITOS DEL SCRIPT
- Se ejecuta con \`bash <script>\` desde la RAÍZ del repositorio (cwd = raíz).
- Solo LEE archivos. No se conecta a ninguna base de datos, no usa la red, no
  escribe ni modifica nada, y no ejecuta comandos del proyecto que puedan tener
  efectos (nada de migrar, instalar dependencias ni levantar servidores).
- Termina en menos de 20 segundos.
- Usa solo herramientas que ya estén disponibles en el sistema. Podés escribirlo
  en bash, o embeber python3/node si el parseo lo amerita — pero verificá que el
  intérprete que elijas exista antes de depender de él.
- Imprime EXCLUSIVAMENTE el JSON en stdout (los mensajes de diagnóstico van a
  stderr). Si algo falla, terminá con código distinto de cero y el motivo en
  stderr.
- Tiene que ser robusto: si un archivo no existe, que no reviente.

CONTRATO DE SALIDA (exacto)
${SCRIPT_CONTRACT}

Reglas del contrato:
- "entities": una por tabla/modelo. "name" es obligatorio y único.
- "fields": columnas declaradas. "nullable" y "primaryKey" son booleanos;
  "default" es opcional.
- "relations": UNA POR CADA foreign key declarada, con la DIRECCIÓN correcta:
  "from" es la entidad HIJA (la que tiene la clave foránea) y "to" es la entidad
  PADRE a la que apunta. "fromField" es la columna que guarda la referencia.
  Esta dirección es lo más importante del diagrama: no la inviertas.
  Solo relaciones con foreign key real: una asociación que el esquema no declara
  como tal (por ejemplo una polimórfica \`<algo>_type\` + \`<algo>_id\`, que por
  definición no puede tener foreign key) NO se emite. El diagrama muestra lo que
  la base declara, no lo que el código infiere.
- "from" y "to" deben coincidir exactamente con un "name" de "entities"; las
  relaciones que apunten a entidades no declaradas se descartan.
- "sourceFile" (ruta relativa a la raíz del repo) y "sourceLine" permiten saltar
  a la declaración: completalos siempre que puedas.
- "dialect": etiqueta corta del stack detectado (por ejemplo "rails", "prisma",
  "django", "sql").

VERIFICACIÓN OBLIGATORIA antes de responder
Ejecutá el script y comprobá que: imprime JSON válido, la cantidad de entidades
coincide con las tablas realmente declaradas en el código, y las relaciones
apuntan de hijo a padre. Corregilo hasta que sea así.

RESPUESTA
Devolvé ÚNICAMENTE el contenido final del script, sin explicaciones y sin
envolverlo en bloques de markdown. La primera línea debe ser un shebang.`;
}

export interface GenerateOptions {
  /** Repo root the agent inspects (the task's worktree). */
  cwd: string;
  /** Display name, for the prompt. */
  repoName: string;
  /** Command to invoke the agent (config.defaultAgentCommand). */
  agentCommand: string;
  /** Optional model override. */
  model?: string;
}

export interface GenerateResult {
  script: string;
  /** stderr from the agent, useful when it went wrong. */
  log: string;
}

/**
 * Ask a Claude Code agent to write the extractor for this repo. Runs in print
 * mode with READ-ONLY tools: the agent inspects the code and returns the script
 * as text; writing it to disk is this server's job, not the agent's.
 */
export async function generateScript(
  opts: GenerateOptions,
): Promise<GenerateResult> {
  let stdout: string;
  let stderr = "";
  try {
    const res = await execFileAsync(opts.agentCommand, agentArgs(opts), {
      cwd: opts.cwd,
      timeout: GENERATE_TIMEOUT_MS,
      maxBuffer: MAX_OUTPUT_BYTES,
    });
    stdout = res.stdout;
    stderr = res.stderr;
  } catch (err) {
    throw agentFailure(err, opts.agentCommand);
  }

  const script = stripFences(stdout);
  if (!script.trim()) {
    throw new SchemaScriptError("El agente no devolvió ningún script.");
  }
  return { script, log: stderr };
}

/** Cómo se invoca al agente: print mode, herramientas de SÓLO LECTURA, texto plano. */
function agentArgs(opts: GenerateOptions): string[] {
  const args = [
    "-p",
    buildGenerationPrompt(opts.repoName),
    "--allowedTools",
    "Read",
    "Glob",
    "Grep",
    "Bash",
    "--permission-mode",
    "acceptEdits",
    "--output-format",
    "text",
  ];
  if (opts.model) args.push("--model", opts.model);
  return args;
}

/**
 * Traduce el fallo del agente al mensaje que va a leer el usuario en el panel.
 * Los dos modos que se distinguen —comando inexistente y corte por timeout— no
 * dejan stderr útil, así que sin este nombre propio se verían como "el agente
 * falló: " y nada más.
 */
function agentFailure(err: unknown, agentCommand: string): SchemaScriptError {
  const e = err as NodeJS.ErrnoException & { stderr?: string; killed?: boolean };
  if (e.code === "ENOENT") {
    return new SchemaScriptError(
      `No se encontró el comando \`${agentCommand}\` para generar el script.`,
    );
  }
  if (e.killed) {
    return new SchemaScriptError(
      `El agente superó los ${GENERATE_TIMEOUT_MS / 60_000} minutos y fue interrumpido.`,
    );
  }
  return new SchemaScriptError(
    `El agente falló: ${(e.stderr ?? e.message ?? "").trim().slice(0, 400)}`,
  );
}

/**
 * Agents are asked for a bare script, but a fenced block is the most likely
 * deviation, so unwrap it rather than writing an unrunnable file.
 */
export function stripFences(text: string): string {
  const trimmed = text.trim();
  const fenced = /^```[a-zA-Z]*\n([\s\S]*?)\n?```$/.exec(trimmed);
  return (fenced ? fenced[1] : trimmed).trim() + "\n";
}

/** Write the script + its metadata, making it executable. */
export async function saveScript(opts: {
  dataDir: string;
  projectRepoId: string;
  script: string;
  summary: string;
  now: string;
}): Promise<string> {
  const file = scriptPathFor(opts.dataDir, opts.projectRepoId);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, opts.script, { mode: 0o755 });
  await fs.writeFile(
    metaPathFor(opts.dataDir, opts.projectRepoId),
    JSON.stringify({ generatedAt: opts.now, summary: opts.summary }, null, 2),
  );
  return file;
}

/** Delete a repo's script and metadata (idempotent). */
export async function deleteScript(
  dataDir: string,
  projectRepoId: string,
): Promise<void> {
  await fs.rm(scriptPathFor(dataDir, projectRepoId), { force: true });
  await fs.rm(metaPathFor(dataDir, projectRepoId), { force: true });
}

/** Assemble the graph a repo's script produced. */
export function toGraph(repoName: string, result: ExtractResult): SchemaGraph {
  return {
    repoName,
    dialect: result.dialect,
    sourceFiles: [
      ...new Set(
        [...result.entities, ...result.relations]
          .map((x) => x.sourceFile)
          .filter((f): f is string => typeof f === "string" && f.length > 0),
      ),
    ].sort(),
    entities: [...result.entities].sort((a, b) => a.name.localeCompare(b.name)),
    relations: [...result.relations].sort(
      (a, b) => a.from.localeCompare(b.from) || a.fromField.localeCompare(b.fromField),
    ),
  };
}

/* ── tiny guards ──────────────────────────────────────────────────────── */

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function asString(v: unknown): string | null {
  return typeof v === "string" ? v : null;
}

function asPositiveInt(v: unknown): number | null {
  return typeof v === "number" && Number.isInteger(v) && v >= 0 ? v : null;
}
